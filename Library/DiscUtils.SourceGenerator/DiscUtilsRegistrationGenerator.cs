using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace DiscUtils.SourceGenerator;

[Generator]
public class DiscUtilsRegistrationGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Register for attribute syntax
        var classDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => IsSyntaxTargetForGeneration(s),
                transform: static (ctx, _) => GetSemanticTargetForGeneration(ctx))
            .Where(static m => m is not null);

        // Combine the selected classes with the compilation
        var compilationAndClasses = context.CompilationProvider.Combine(classDeclarations.Collect());

        // Generate the source
        context.RegisterSourceOutput(compilationAndClasses,
            static (spc, source) => Execute(source.Left, source.Right!, spc));
    }

    private static bool IsSyntaxTargetForGeneration(SyntaxNode node)
    {
        return node is ClassDeclarationSyntax classDeclaration &&
               classDeclaration.AttributeLists.Count > 0;
    }

    private static ClassInfo? GetSemanticTargetForGeneration(GeneratorSyntaxContext context)
    {
        var classDeclaration = (ClassDeclarationSyntax)context.Node;
        var symbol = context.SemanticModel.GetDeclaredSymbol(classDeclaration);

        if (symbol is null)
            return null;

        // Check for our target attributes
        var hasVfsAttribute = symbol.GetAttributes().Any(ad =>
            ad.AttributeClass?.Name == "VfsFileSystemFactoryAttribute" ||
            ad.AttributeClass?.ToDisplayString() == "DiscUtils.Vfs.VfsFileSystemFactoryAttribute");

        var virtualDiskAttribute = symbol.GetAttributes().FirstOrDefault(ad =>
            ad.AttributeClass?.Name == "VirtualDiskFactoryAttribute" ||
            ad.AttributeClass?.ToDisplayString() == "DiscUtils.Internal.VirtualDiskFactoryAttribute");

        var hasLogicalVolumeAttribute = symbol.GetAttributes().Any(ad =>
            ad.AttributeClass?.Name == "LogicalVolumeFactoryAttribute" ||
            ad.AttributeClass?.ToDisplayString() == "DiscUtils.Internal.LogicalVolumeFactoryAttribute");

        var virtualDiskTransportAttribute = symbol.GetAttributes().FirstOrDefault(ad =>
            ad.AttributeClass?.Name == "VirtualDiskTransportAttribute" ||
            ad.AttributeClass?.ToDisplayString() == "DiscUtils.Internal.VirtualDiskTransportAttribute");

        if (!hasVfsAttribute && virtualDiskAttribute is null && !hasLogicalVolumeAttribute && virtualDiskTransportAttribute is null)
            return null;

        var fullTypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var assemblyName = symbol.ContainingAssembly.Name;

        string? diskType = null;
        string[]? fileExtensions = null;
        string? transportScheme = null;

        if (virtualDiskAttribute is not null)
        {
            if (virtualDiskAttribute.ConstructorArguments.Length >= 1)
            {
                diskType = virtualDiskAttribute.ConstructorArguments[0].Value?.ToString();
            }
            if (virtualDiskAttribute.ConstructorArguments.Length >= 2)
            {
                var extensionsArg = virtualDiskAttribute.ConstructorArguments[1].Value?.ToString();
                if (extensionsArg != null)
                {
                    fileExtensions = extensionsArg.Replace(".", "").Split(',');
                }
            }
        }

        if (virtualDiskTransportAttribute is not null)
        {
            if (virtualDiskTransportAttribute.ConstructorArguments.Length >= 1)
            {
                transportScheme = virtualDiskTransportAttribute.ConstructorArguments[0].Value?.ToString();
            }
        }

        return new ClassInfo(
            fullTypeName,
            assemblyName,
            hasVfsAttribute,
            virtualDiskAttribute is not null,
            hasLogicalVolumeAttribute,
            virtualDiskTransportAttribute is not null,
            diskType,
            fileExtensions,
            transportScheme);
    }

    private static void Execute(Compilation compilation, IEnumerable<ClassInfo> classes, SourceProductionContext context)
    {
        if (!classes.Any())
            return;

        var groupedByAssembly = classes.GroupBy(c => c.AssemblyName);

        foreach (var assemblyGroup in groupedByAssembly)
        {
            var assemblyName = assemblyGroup.Key;
            var safeAssemblyName = assemblyName.Replace(".", "_");

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("namespace DiscUtils.Setup;");
            sb.AppendLine();
            sb.AppendLine("/// <summary>");
            sb.AppendLine($"/// AOT-compatible registration for {assemblyName}");
            sb.AppendLine("/// </summary>");
            sb.AppendLine($"public static class {safeAssemblyName}_GeneratedRegistration");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Registers all types in this assembly with the DiscUtils managers");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static void Register()");
            sb.AppendLine("    {");

            // Register VFS File Systems
            var vfsClasses = assemblyGroup.Where(c => c.HasVfsFileSystemFactoryAttribute).ToList();
            if (vfsClasses.Any())
            {
                sb.AppendLine("        // Register VFS File System Factories");
                foreach (var classInfo in vfsClasses)
                {
                    sb.AppendLine($"        global::DiscUtils.FileSystemManager.RegisterFileSystems(new {classInfo.FullTypeName}());");
                }
                sb.AppendLine();
            }

            // Register Virtual Disk Factories
            var virtualDiskClasses = assemblyGroup.Where(c => c.HasVirtualDiskFactoryAttribute).ToList();
            if (virtualDiskClasses.Any())
            {
                sb.AppendLine("        // Register Virtual Disk Factories");
                foreach (var classInfo in virtualDiskClasses)
                {
                    sb.AppendLine($"        {{");
                    sb.AppendLine($"            var factory = new {classInfo.FullTypeName}();");
                    if (classInfo.DiskType != null)
                    {
                        sb.AppendLine($"            global::DiscUtils.VirtualDiskManager.TypeMap.Add(\"{classInfo.DiskType}\", factory);");
                    }
                    if (classInfo.FileExtensions != null && classInfo.FileExtensions.Length > 0)
                    {
                        foreach (var ext in classInfo.FileExtensions)
                        {
                            sb.AppendLine($"            global::DiscUtils.VirtualDiskManager.ExtensionMap.Add(\"{ext}\", factory);");
                        }
                    }
                    sb.AppendLine($"        }}");
                }
                sb.AppendLine();
            }

            // Register Logical Volume Factories
            var logicalVolumeClasses = assemblyGroup.Where(c => c.HasLogicalVolumeFactoryAttribute).ToList();
            if (logicalVolumeClasses.Any())
            {
                sb.AppendLine("        // Register Logical Volume Factories");
                foreach (var classInfo in logicalVolumeClasses)
                {
                    sb.AppendLine($"        global::DiscUtils.VolumeManager.RegisterLogicalVolumeFactory(new {classInfo.FullTypeName}());");
                }
                sb.AppendLine();
            }

            // Register Virtual Disk Transports
            var transportClasses = assemblyGroup.Where(c => c.HasVirtualDiskTransportAttribute).ToList();
            if (transportClasses.Any())
            {
                sb.AppendLine("        // Register Virtual Disk Transports");
                foreach (var classInfo in transportClasses)
                {
                    if (classInfo.TransportScheme != null)
                    {
                        sb.AppendLine($"        global::DiscUtils.VirtualDiskManager.DiskTransports.Add(\"{classInfo.TransportScheme}\", typeof({classInfo.FullTypeName}));");
                    }
                }
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            context.AddSource($"{safeAssemblyName}_GeneratedRegistration.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }

    private record ClassInfo(
        string FullTypeName,
        string AssemblyName,
        bool HasVfsFileSystemFactoryAttribute,
        bool HasVirtualDiskFactoryAttribute,
        bool HasLogicalVolumeFactoryAttribute,
        bool HasVirtualDiskTransportAttribute,
        string? DiskType,
        string[]? FileExtensions,
        string? TransportScheme);
}
